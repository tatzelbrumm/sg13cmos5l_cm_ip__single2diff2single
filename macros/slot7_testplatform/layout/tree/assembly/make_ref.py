"""LVS reference for bias_tree_noab_pd: the source subckts copied unchanged (2026-11-07, Claude).

bias_diodes from macros/bias_tree_pd/netlist/source/bias_ref_pd.spice and bias_tree_noab_pd from
macros/bias_tree_noab_pd/netlist/source/bias_tree_noab_pd.spice, line for line between .subckt and .ends.
Usage: python3 make_ref.py [out.spice]   (default: checks/bias_tree_noab_pd_source_ref.spice)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MAC = os.path.normpath(os.path.join(HERE, "..", "..", "..", ".."))       # macros/
SRC = [(os.path.join(MAC, "bias_tree_pd", "netlist", "source", "bias_ref_pd.spice"), "bias_diodes"),
       (os.path.join(MAC, "bias_tree_noab_pd", "netlist", "source", "bias_tree_noab_pd.spice"), "bias_tree_noab_pd")]


def subckt(path, name):
    out, on = [], False
    for line in open(path):
        w = line.split()
        if w[:2] == [".subckt", name]:
            on = True
        if on:
            out.append(line.rstrip("\n"))
            if w[:1] == [".ends"]:
                return out
    raise SystemExit(f"{name} not found in {path}")


out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "checks", "bias_tree_noab_pd_source_ref.spice")
lines = ["* LVS reference for bias_tree_noab_pd, generated by make_ref.py: source subckts copied unchanged"]
for path, name in SRC:
    lines += ["* from " + os.path.relpath(path, os.path.dirname(MAC))] + subckt(path, name)
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out)
