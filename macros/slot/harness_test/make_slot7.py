#!/usr/bin/env python3
"""make_slot7.py --- build the harness-test slot GDS slot_7.gds (a plumbing demo).

Usage (from the slot repository root, KLayout's python module installed):

    python3 macros/slot/harness_test/make_slot7.py <harness>/magic/slot7_wrapper.mag

ONE SOURCE.  The pin table is read from the regenerated slot7_wrapper.mag of the
harness branch custom-pad-test (every flabel whose text starts with s7_an_).  It is
written to macros/slot/harness_test/slot7_pins.md, and everything else is derived
from it here:  the pins of final/gds/slot_7.gds, and the port lists of
final/vh/slot_7.vh (final/lef/slot_7.lef is written by magic from the GDS, see
build_views.sh;  final/lib/slot_7.lib carries no pins).

What the GDS contains (top cell slot_7, 537.15 x 273 um, from
macros/slot/layout/klayout/slot.klay.gds):
  * the frame's harness pins and supplies, unchanged;
  * the old pad pins s7_an[0], s7_an[1], s7_an_0_esd removed;
  * 13 Metal3 pins exactly where the wrapper has them (drawing + pin + label);
  * stand-in wiring S2D outp -> D2S vinp and S2D outn -> D2S vinn:  a Metal3 stub
    from each pin, Via3, a vertical Metal4 line;
  * for the 9 other pad pins a labelled stub:  Metal3 stub, Via3, a Metal4 landing
    pad with a pin shape and a label of the same net name.
No device, no circuit.  The wiring is a stand-in, see harness_test/README.md.
"""
import os
import re
import sys

import klayout.db as db

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
FRAME = os.path.join(ROOT, 'macros', 'slot', 'layout', 'klayout', 'slot.klay.gds')
OUT_GDS = os.path.join(ROOT, 'final', 'gds', 'slot_7.gds')
OUT_VH = os.path.join(ROOT, 'final', 'vh', 'slot_7.vh')
OUT_TABLE = os.path.join(HERE, 'slot7_pins.md')

# IHP SG13CMOS5L GDS layers
M3, M3PIN, M3TXT = (30, 0), (30, 2), (30, 25)
V3 = (49, 0)
M4, M4PIN, M4TXT = (50, 0), (50, 2), (50, 25)

PADS = {'s7_an_0': ('s7_an[0]', 'sg13cmos5l_IOPadSingle2Diff'),
        's7_an_1': ('s7_an[1]', 'sg13cmos5l_IOPadDiff2Single')}
WIRES = [('s7_an_0_outp', 's7_an_1_vinp', 530.0),   # (from, to, x of the Metal4 line)
         ('s7_an_0_outn', 's7_an_1_vinn', 528.0)]
STUB_X = {'s7_an_1_iref': 533.0, 's7_an_1_en_3v3_b': 531.5, 's7_an_1_en_3v3': 530.0}
STUB_X_DEFAULT = 533.0


def read_wrapper_pins(magfile):
    """Pins s7_an_* of the wrapper:  name -> (layer, x0, y0, x1, y1) in um.
    The label rectangle marks the pin;  the Metal3 strap under it is
    found by looking for the metal3 rect that contains the label."""
    text = open(magfile).read()
    scale = 0.005 if re.search(r'^magscale 1 2$', text, re.M) else 0.01
    rects, sec = [], None
    for line in text.splitlines():
        if line.startswith('<< '):
            sec = line.split()[1]
        elif line.startswith('rect ') and sec == 'metal3':
            rects.append(tuple(int(v) for v in line.split()[1:5]))
    pins = {}
    for m in re.finditer(r'^flabel (\S+) (-?\d+) (-?\d+) (-?\d+) (-?\d+) .* (s7_an_\S+)$', text, re.M):
        layer, name = m.group(1), m.group(6)
        lx0, ly0, lx1, ly1 = (int(m.group(i)) for i in range(2, 6))
        strap = [r for r in rects if r[0] <= lx0 and r[2] >= lx1 and r[1] <= ly0 and r[3] >= ly1]
        # union of the rects on the strap's rows (magic splits it around the label)
        x0 = min(r[0] for r in strap); x1 = max(r[2] for r in strap)
        pins[name] = (layer, x0 * scale, ly0 * scale, max(x1, lx1) * scale, ly1 * scale)
    return pins


def write_table(pins):
    with open(OUT_TABLE, 'w') as f:
        f.write('# slot_7 pad pins (generated by make_slot7.py from the harness slot7_wrapper.mag)\n\n')
        f.write('Single source for slot_7.gds and final/vh/slot_7.vh (and, via magic, final/lef/slot_7.lef).\n')
        f.write('Coordinates in um, slot-local (origin = lower left of the 537.15 x 273 um slot).\n\n')
        f.write('| signal | pad | pad pin | layer | edge | x0 | x1 | y0 | y1 |\n|---|---|---|---|---|---|---|---|---|\n')
        for name in sorted(pins, key=lambda n: pins[n][2]):
            layer, x0, y0, x1, y1 = pins[name]
            core = name[:7]
            pad, cell = PADS[core]
            f.write(f'| {name} | {pad} ({cell}) | {name[8:]} | {layer} | right | {x0:.3f} | {x1:.3f} | {y0:.3f} | {y1:.3f} |\n')


def box(x0, y0, x1, y1, dbu):
    return db.Box(round(x0 / dbu), round(y0 / dbu), round(x1 / dbu), round(y1 / dbu))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    pins = read_wrapper_pins(sys.argv[1])
    if len(pins) != 13:
        sys.exit(f'expected 13 s7_an_* pins in the wrapper, found {len(pins)}: {sorted(pins)}')
    write_table(pins)

    ly = db.Layout()
    ly.read(FRAME)
    top = ly.top_cells()[0]
    top.name = 'slot_7'
    dbu = ly.dbu
    L = {k: ly.layer(*k) for k in (M3, M3PIN, M3TXT, V3, M4, M4PIN, M4TXT)}

    # Remove the old pad pins (right edge, Metal3 drawing, pin and text)
    edge = box(530, 0, 537.15, 273, dbu)
    for k in (M3, M3PIN, M3TXT):
        for s in list(top.shapes(L[k]).each()):
            if s.is_text():
                if s.text_string.startswith('s7_an'):
                    top.shapes(L[k]).erase(s)
            elif s.bbox().inside(edge) or s.bbox().overlaps(box(535, 0, 537.15, 273, dbu)):
                top.shapes(L[k]).erase(s)

    def m3(x0, y0, x1, y1):
        top.shapes(L[M3]).insert(box(x0, y0, x1, y1, dbu))

    def via3(xc, yc):
        top.shapes(L[V3]).insert(box(xc - 0.095, yc - 0.095, xc + 0.095, yc + 0.095, dbu))

    def label(k, name, x, y):
        top.shapes(L[k]).insert(db.Text(name, db.Trans(round(x / dbu), round(y / dbu))))

    # The 13 pins:  drawing + pin + label on Metal3
    yc = {}
    for name, (layer, x0, y0, x1, y1) in pins.items():
        m3(x0, y0, x1, y1)
        top.shapes(L[M3PIN]).insert(box(x0, y0, x1, y1, dbu))
        label(M3TXT, name, (x0 + x1) / 2, (y0 + y1) / 2)
        yc[name] = ((y0 + y1) / 2, x0, y0, y1)

    def stub(name, xv):
        # Metal3 stub from the pin to 0.15 um beyond the Via3 at xv, same width as the pin
        y, x0, y0, y1 = yc[name]
        m3(xv - 0.15, y0, x0 + 0.01, y1)
        via3(xv, y)
        return y

    # Stand-in wiring outp -> vinp, outn -> vinn (vertical Metal4 lines, 0.3 um wide)
    for a, b, xv in WIRES:
        ya, yb = stub(a, xv), stub(b, xv)
        top.shapes(L[M4]).insert(box(xv - 0.15, min(ya, yb) - 0.15, xv + 0.15, max(ya, yb) + 0.15, dbu))

    # Labelled stubs for the support nets:  Metal3 stub, Via3, 0.4 x 0.4 Metal4 pad with pin + label
    wired = {n for w in WIRES for n in w[:2]}
    for name in sorted(set(pins) - wired):
        xv = STUB_X.get(name, STUB_X_DEFAULT)
        y = stub(name, xv)
        top.shapes(L[M4]).insert(box(xv - 0.2, y - 0.2, xv + 0.2, y + 0.2, dbu))
        top.shapes(L[M4PIN]).insert(box(xv - 0.2, y - 0.2, xv + 0.2, y + 0.2, dbu))
        label(M4TXT, name, xv, y)

    os.makedirs(os.path.dirname(OUT_GDS), exist_ok=True)
    opt = db.SaveLayoutOptions()
    opt.write_context_info = False
    ly.write(OUT_GDS, opt)

    # Verilog header:  harness ports of the frame (texts on the left edge) + the 13 pad pins
    names = set()
    for k in [(30, 25), (10, 25), (126, 25)]:
        li = ly.find_layer(*k)
        if li is None:
            continue
        for s in top.shapes(li).each():
            if s.is_text():
                names.add(s.text_string)
    buses, scalars = {}, []
    for n in sorted(names):
        m = re.match(r'^(.*)\[(\d+)\]$', n)
        if m:
            buses.setdefault(m.group(1), []).append(int(m.group(2)))
        else:
            scalars.append(n)
    os.makedirs(os.path.dirname(OUT_VH), exist_ok=True)
    supplies = [n for n in scalars if re.match(r'^v(dd|ss)_', n)]
    with open(OUT_VH, 'w') as f:
        f.write('// slot_7 (harness-test plumbing demo), generated by macros/slot/harness_test/make_slot7.py\n')
        f.write('module slot_7 (\n`ifdef USE_POWER_PINS\n')
        for n in supplies:
            f.write(f'    inout {n},\n')
        f.write('`endif\n')
        ports = [f'    inout [{max(v)}:{min(v)}] {b}' for b, v in sorted(buses.items())]
        ports += [f'    inout {n}' for n in scalars if n not in supplies]
        f.write(',\n'.join(ports) + '\n);\nendmodule\n')
    print(f'wrote {OUT_GDS}, {OUT_VH}, {OUT_TABLE}:  {len(pins)} pad pins')


main()
