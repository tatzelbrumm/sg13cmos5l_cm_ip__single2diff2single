from pathlib import Path

MAC = Path(__file__).resolve().parents[2]
TOP = "pad_ref_rb"
SYM = MAC / TOP / "schematic/xschem" / f"{TOP}.sym"
NET = {"vdd": "vddb", "vss": "0"}          # harness nets of the DUT pins (others: same name)
S2D_TPL = MAC / "sg13cmos5l_IOPadSingle2Diff/verification/cace/templates/sg13cmos5l_IOPadSingle2Diff_tb_dc.sch"
tpl = S2D_TPL.read_text().splitlines()
i0 = next(i for i, l in enumerate(tpl) if l.startswith("C {en_ctrl_3v3.sym}"))
HARNESS = [l for l in tpl[i0:] if not l.startswith("T ")]

MODEL = r""".lib cornerMOShv.lib mos_CACE\{corner_mos\}
.lib cornerMOSlv.lib mos_CACE\{corner_mos\}
.lib cornerRES.lib res_CACE\{corner_r=typ\}
.lib cornerCAP.lib cap_CACE\{corner_c=typ\}
.lib cornerPNP.lib CACE\{corner_pnp=typ\}
.lib cornerDIO.lib dio_tt"""

SOURCES = r"""* ---- supplies: iovdd = IO ring, vddb = the block's supply (same voltage, measured), vcore = 1.2 V core ring
Vio iovdd 0 dc CACE\{vdd\}
Vbk vddb 0 dc CACE\{vdd\}
Vcore vcore 0 CACE\{vddl=1.2\}
* ---- slot-side controls (1.2 V logic) and the slot supplies seen by the presence detectors
Ven en 0 CACE\{en=1.2\}
Vs0 s0 0 CACE[(CACE\{sel=0\} % 2)*CACE\{vddl=1.2\}]
Vs1 s1 0 CACE[floor(CACE\{sel=0\} / 2)*CACE\{vddl=1.2\}]
Vs12 s12 0 CACE\{vs12=1.2\}
Vs33 s33 0 CACE\{vs33=3.3\}
* ---- harness iDAC: a sourced current from a PMOS mirror on its own 3.3 V supply
Vext vext 0 3.3
Iext xg 0 CACE\{ibias=5e-6\}
XEd xg xg vext vext sg13_hv_pmos w=5u l=6u
XEm ibias xg vext vext sg13_hv_pmos w=5u l=6u"""

NGSPICE = r""".include CACE\{DUT_path\}
.temp CACE\{temp\}
.options savecurrents method=gear reltol=1e-4 abstol=1e-15 gmin=1e-15 SEED=CACE[CACE\{seed=12345\} + CACE\{iterations=0\}]
.option warn=1
.control
op
let vc = v(vcm)
let vr = v(vref)
let ib = -i(vbk)
echo $&vc $&vr $&ib > CACE\{filename\}_CACE\{N\}.data
.endc"""


def code(name, x, y, value, top=False, fmt=False):
    head = f"C {{devices/code_shown.sym}} {x} {y} 0 0 {{name={name} " + \
           ("only_toplevel=true\nformat=\"tcleval( @value )\"" if top else
            ("simulator=ngspice only_toplevel=false" if name == "NGSPICE" else "only_toplevel=false"))
    return [head, 'value="', value, '"}']


def sym_pins(sym):
    """{pin: (x, y)} from the B 5 pin boxes of an xschem symbol (box centre)."""
    out = {}
    for m in re.finditer(r"^B 5 (\S+) (\S+) (\S+) (\S+) \{[^}]*name=(\S+)", sym.read_text(), re.M):
        x1, y1, x2, y2 = (float(m.group(k)) for k in range(1, 5))
        out[m.group(5)] = ((x1 + x2) / 2, (y1 + y2) / 2)
    return out


def template(block, title, x0=1200, y0=0):
    o = ["v {xschem version=3.4.8RC file_version=1.3}", "G {}", "K {}", "V {}", "S {}", "F {}", "E {}",
         f"T {{CACE template: {title}}} 0 -600 0 0 0.6 0.6 {{}}",
         f"T {{{block}: replica bias; sources and analysis are in the code blocks (generated by gen_cace.py)}} 0 -560 0 0 0.3 0.3 {{}}",
         f"C {{{block}.sym}} {x0} {y0} 0 0 {{name=x1}}"]
    for i, (p, (x, y)) in enumerate(sym_pins(SYM).items()):
        flip = 0 if x < 0 else 1          # label text away from the symbol body
        o.append(f"C {{devices/lab_pin.sym}} {x0 + x:g} {y0 + y:g} 0 {flip} {{name=lp{i} sig_type=std_logic "
                 f"lab={NET.get(p, p)}}}")
    o += code("MODEL", 0, -460, MODEL, top=True) + code("SOURCES", 0, -260, SOURCES) + \
        code("NGSPICE", 1700, -460, NGSPICE)
    o += HARNESS
    return "\n".join(o) + "\n"


