ANY = ("V", "any", "any")
VCM = "Vcm", "Vref", "Ib"


def grp(name, cond, ib, vcm=ANY, vref=ANY, collate=False):
    """one parameter group; vcm / vref = (display, lo, hi), Ib limit ib uA."""
    spec = {"Vcm": ("Vcm: " + vcm[0], "V", vcm[1], vcm[2]) if vcm is not ANY else ("Vcm", "V", "any", "any"),
            "Vref": ("Vref: " + vref[0], "V", vref[1], vref[2]) if vref is not ANY else ("Vref", "V", "any", "any"),
            "Ib": ("Supply current (tree + both blocks, without the reference)", "uA", "any", ib)}
    return dict(name=name, tpl=f"{TOP}_tb_dc.sch", vars=list(VCM), spec=spec, cond=cond, collate=collate)


