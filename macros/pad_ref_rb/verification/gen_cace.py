"""CACE suite of pad_ref_rb (bias_tree_rb + vcm_rb + vref_s2d_rb on one enable): template (xschem sheet with code blocks,
the DUT next to en_ctrl_3v3 and bias_gen_pd as in the pads' templates; the harness lines are copied from
sg13cmos5l_IOPadSingle2Diff_tb_dc.sch; the DUT's lab_pins sit on the pins read from pad_ref_rb.sym) and the yaml.
Limits: the bands measured in the gap runs (docs/replica_bias/).
Until 2026-11-07 vcm_rb and vref_s2d_rb had a suite each (macros/<block>/verification/cace, moved to
verification/baseline/cace_own_tree/); since then both hang on the shared tree and are characterized together.

usage: python3 -I gen_cace.py   (writes macros/pad_ref_rb/verification/cace/{pad_ref_rb.yaml, templates/})
"""
