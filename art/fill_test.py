#!/usr/bin/env python3
"""Does the PDK filler keep out of the art's no-fill box?  Writes art/fill_test.md.

usage: fill_test.py [reference_gds_without_markers]
The PDK filler (libs.tech/klayout/tech/scripts/filler.py) fills only inside the holes of a seal ring (layer 39/0); the bare slot has none,
so a synthetic ring is added around the slot in scratch copies. The merged GDS (with no-fill markers) is filled and the filler shapes
(datatype 22) inside the marker box are counted; an optional reference GDS without markers (e.g. git show art-rev3-m1-m4:art/slot7_with_art.gds)
is filled the same way as a control.
"""
import os, subprocess, sys, tempfile
import klayout.db as db
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import json
st = json.load(open(os.path.join(HERE, "build_stats.json")))
bx0, by0, bx1, by1 = st["nofill_box_um_slot_frame"]
box = db.Region(db.Box(*[int(round(v * 1000)) for v in (bx0, by0, bx1, by1)]))
env = dict(os.environ, PDK_ROOT="/foss/pdks", PDK="ihp-sg13cmos5l", KLAYOUT_PATH="/foss/pdks/ihp-sg13cmos5l/libs.tech/klayout")
FILLER = "/foss/pdks/ihp-sg13cmos5l/libs.tech/klayout/tech/scripts/filler.py"
W = tempfile.mkdtemp(prefix="tughra_fill_")
LAYERS = [(1, "Activ"), (5, "GatPoly"), (8, "Metal1"), (10, "Metal2"), (30, "Metal3"), (50, "Metal4"), (126, "TopMetal1")]


def run(name, gds):
    ly = db.Layout(); ly.read(gds); top = ly.cell("slot_7")
    top.shapes(ly.layer(39, 0)).insert(db.Region(db.Box(-10000, -10000, 547150, 283000)) - db.Region(db.Box(0, 0, 537150, 273000)))
    seal = os.path.join(W, name + "_seal.gds"); out = os.path.join(W, name + "_filled.gds")
    ly.write(seal)
    subprocess.run(["klayout", "-n", "sg13cmos5l", "-zz", "-r", FILLER, "-rd", f"output_file={out}", seal], env=env, capture_output=True, timeout=600)
    f = db.Layout(); f.read(out); t = f.cell("slot_7")
    rows = []
    for l, n in LAYERS:
        li = f.find_layer(l, 22)
        r = db.Region(t.begin_shapes_rec(li)) if li is not None else db.Region()
        rows.append((n, f"{l}/22", r.count(), r.interacting(box).count(), (r & box).area() * 1e-6))
    return rows


res = {"with_markers": run("rev4", os.path.join(HERE, "slot7_with_art.gds"))}
if len(sys.argv) > 1:
    res["without_markers (control)"] = run("ctrl", sys.argv[1])
L = ["# Filler test (generated by fill_test.py)", "",
     f"PDK filler script on a copy of the merged GDS with a synthetic seal ring (39/0). Marker box (um, slot frame): ({bx0}, {by0}) - ({bx1}, {by1}).", ""]
for k, rows in res.items():
    L += [f"## {k}", "", "| filler layer | GDS | filler shapes in slot | shapes touching the box | filler area inside the box (um2) |", "|---|---|---|---|---|"]
    L += [f"| {n} | {g} | {c} | {i} | {a:.0f} |" for n, g, c, i, a in rows]
    L.append("")
open(os.path.join(HERE, "fill_test.md"), "w").write("\n".join(L))
print("\n".join(L))
