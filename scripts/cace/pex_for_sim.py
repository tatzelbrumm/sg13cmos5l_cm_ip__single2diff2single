"""Copy an extracted (PEX) netlist for simulation: optionally set mm_ok=1 on the mismatch devices, and tie the nodes that
only capacitors touch to a net.

Usage: pex_for_sim.py <in.spice> <out.spice> [--mm-ok] [--tie <net> <ohm>]
  --mm-ok   The PDK switches local mismatch on per instance with mm_ok=1 (in the *_mismatch model sections), and xschem
            writes it into the schematic netlist only: magic and KLayout-PEX leave it out, so a Monte Carlo run on an
            extracted netlist draws nothing for those devices. This appends mm_ok=1 to the X lines of sg13_hv_nmos /
            sg13_hv_pmos / sg13_lv_nmos / sg13_lv_pmos / rhigh / rppd / rsil (pnpMPA has no mismatch model).
  --tie     A node that only capacitors touch has no DC path: ngspice's op matrix is singular, it falls back to gmin
            stepping or a transient op, and can land on a wrong operating point. This adds R<k> <node> <net> <ohm>
            before .ends for each such node (the subckt's ports excepted).
Everything else is copied unchanged. Added 2026-10-30 (cloud session C1) for the bias_sel_pd core views in
macros/bias_sel_pd/verification/cace/templates/cores/ (make cores-pex-sim there).
"""
import sys

MM = {'sg13_hv_nmos', 'sg13_hv_pmos', 'sg13_lv_nmos', 'sg13_lv_pmos', 'rhigh', 'rppd', 'rsil'}

def model(tokens):
    # the model is the last token of an X line that is not a parameter (name=value)
    for t in reversed(tokens[1:]):
        if '=' not in t:
            return t.lower()
    return ''

def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__)
    src, dst, opts = argv[0], argv[1], argv[2:]
    mm_ok = '--mm-ok' in opts
    tie = None
    if '--tie' in opts:
        i = opts.index('--tie')
        tie = (opts[i + 1], opts[i + 2])
    # join continuation lines into statements
    stmts = []
    for ln in open(src).read().splitlines():
        if ln.startswith('+') and stmts:
            stmts[-1].append(ln)
        else:
            stmts.append([ln])
    ports, dev, cap = [], set(), set()
    for st in stmts:
        t = ' '.join(l.lstrip('+') for l in st).split()
        if not t:
            continue
        if t[0].lower() == '.subckt':
            ports = t[2:]
        elif t[0][0] in 'Xx':
            dev.update([x for x in t[1:] if '=' not in x][:-1])
        elif t[0][0] in 'RrLlVvIiEeGgFfHhDdMmQq':
            dev.update(t[1:3])
        elif t[0][0] in 'Cc':
            cap.update(t[1:3])
    floating = sorted(cap - dev - set(ports))
    n_mm, out = 0, []
    for st in stmts:
        t = ' '.join(l.lstrip('+') for l in st).split()
        if mm_ok and t and t[0][0] in 'Xx' and model(t) in MM and not any(x.lower().startswith('mm_ok=') for x in t):
            st[-1] = st[-1] + ' mm_ok=1'
            n_mm += 1
        if tie and t and t[0].lower() == '.ends':
            out += ['Rtie%d %s %s %s' % (k, n, tie[0], tie[1]) for k, n in enumerate(floating)]
        out.extend(st)
    what = []
    if mm_ok:
        what.append('mm_ok=1 on %d devices' % n_mm)
    if tie:
        what.append('%d capacitor-only nodes tied to %s through %s Ohm' % (len(floating), tie[0], tie[1]))
    head = '* generated by scripts/cace/pex_for_sim.py from %s: %s' % (src, '; '.join(what) or 'copy')
    open(dst, 'w').write('\n'.join([head] + out) + '\n')
    print('%s -> %s: %s' % (src, dst, '; '.join(what) or 'copy'))

if __name__ == '__main__':
    main(sys.argv[1:])
